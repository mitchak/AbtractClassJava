    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {// GEN-FIRST:event_jButton2ActionPerformed
        // Dibujo de figura usando el controlador y manteniendo la lógica separada de la
        // interfaz
        c.creacionFigura(color, txtDescripcion.getText(), txtVertice1X.getText(), txtVertice1Y.getText(),
                txtVertice2X.getText(), txtVertice2Y.getText(), txtVertice3X.getText(), txtVertice3Y.getText(),
                txtVertice4X.getText(), txtVertice4Y.getText());
        Figura figura = c.getFigura();
        if (figura != null) {
            dibujoJpanel.setFigura(figura);
            resultadoLabel.setText(c.calcularArea());
        }
    }// GEN-LAST:event_jButton2ActionPerformed

